export const courseCategories = Array.from(new Set(courses.map((course) => course.category)));
export const courseLevels: CourseLevel[] = ["مبتدئ", "متوسط", "متقدم"];
export const courseLanguages = Array.from(new Set(courses.map((course) => course.language)));

export function getCourse(slug: string) {
  return courses.find((course) => course.slug === slug);
}

export function getRelatedCourses(course: Course, limit = 3) {
  return courses
    .filter((item) => item.slug !== course.slug && (item.category === course.category || item.tags.some((tag) => course.tags.includes(tag))))
    .slice(0, limit);
}

export function priceLabel(course: Course) {
  if (course.priceType === "free") return "مجاني";
  if (course.priceType === "comingSoon") return "قريبًا";
  return course.priceMAD ? `${course.priceMAD} درهم` : "مدفوع";
}
