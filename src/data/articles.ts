function sentenceList(items: string[]) {
  return items.map((item) => `• ${item}`).join("\n");
}

function sectionsFor(seed: ArticleSeed): ArticleSection[] {
  const sections: ArticleSection[] = [
    {
      heading: "الفكرة الأساسية",
      body: seed.intro,
    },
    {
      heading: "خطوات عملية",
      body: seed.steps.join(" ") + " اجعل كل خطوة مكتوبة حتى لا تبقى الخطة في ذهنك فقط.",
    },
    {
      heading: seed.checklistTitle,
      body: sentenceList(seed.checklist),
    },
  ];

  if (seed.mistakes?.length) {
    sections.push({
      heading: "أخطاء يجب تجنبها",
      body: sentenceList(seed.mistakes),
    });
  }

  if (seed.verify) {
    sections.push({
      heading: "تنبيه حول المعلومات الرسمية",
      body: officialWarning,
    });
  }

  return sections;
}

